# =========================================================
# COMPOSITION ORDER
# =========================================================


PROFILE_COMPOSITION_ORDER = (
    "research",
    "career",
    "policy",
    "contract",
)


# =========================================================
# ONTOLOGY PROFILE COMPOSITION
# =========================================================


def compose_ontology_profiles(
    names: (
        list[str]
        | tuple[str, ...]
        | set[str]
    ),
) -> OntologyProfile:
    """
    Compose one or more TraceGraph ontology
    profiles into one active ontology.

    Every specialized ontology already contains
    the universal core, therefore composition
    performs a union of:

    - entity types
    - relationship types

    Examples:

        ["policy", "contract"]
            ->
        policy+contract

        ["research", "career"]
            ->
        research+career

        []
            ->
        general

    Composition is canonical and
    order-independent.

    Therefore:

        ["policy", "contract"]

    and:

        ["contract", "policy"]

    both produce:

        policy+contract

    Stable naming is important because ontology
    profile names participate in:

    - graph extraction cache identity
    - Neo4j provenance
    - document metadata
    - API responses
    """

    normalized_names: set[str] = set()

    # -------------------------------------------------
    # Normalize and validate requested profiles.
    # -------------------------------------------------

    for name in names:
        normalized = (
            name.strip()
            .casefold()
        )

        if not normalized:
            continue

        if (
            normalized
            not in ONTOLOGY_PROFILES
        ):
            valid_profiles = (
                ", ".join(
                    sorted(
                        ONTOLOGY_PROFILES
                    )
                )
            )

            raise ValueError(
                "Unknown ontology profile "
                f"'{name}'. "
                "Valid profiles: "
                f"{valid_profiles}"
            )

        # -----------------------------------------
        # GENERAL contributes only the universal
        # core.
        #
        # Every specialized profile already
        # contains that core, so GENERAL does not
        # need to appear in a composed name.
        # -----------------------------------------

        if normalized == "general":
            continue

        normalized_names.add(
            normalized
        )

    # -------------------------------------------------
    # No specialized profiles:
    #
    # Universal-core-only ontology.
    # -------------------------------------------------

    if not normalized_names:
        return GENERAL_ONTOLOGY

    # -------------------------------------------------
    # Canonical ordering.
    #
    # This prevents:
    #
    # contract+policy
    #
    # and:
    #
    # policy+contract
    #
    # from becoming different ontology identities.
    # -------------------------------------------------

    ordered_names = [
        profile_name

        for profile_name
        in PROFILE_COMPOSITION_ORDER

        if (
            profile_name
            in normalized_names
        )
    ]

    # -------------------------------------------------
    # One specialized ontology:
    #
    # Return the registered singleton rather than
    # creating an equivalent duplicate profile.
    # -------------------------------------------------

    if len(ordered_names) == 1:
        return (
            ONTOLOGY_PROFILES[
                ordered_names[0]
            ]
        )

    # -------------------------------------------------
    # Union entity vocabularies.
    # -------------------------------------------------

    entity_types = frozenset(
        entity_type

        for profile_name
        in ordered_names

        for entity_type
        in (
            ONTOLOGY_PROFILES[
                profile_name
            ]
            .entity_types
        )
    )

    # -------------------------------------------------
    # Union relationship vocabularies.
    #
    # Structural relationships CONTAINS and
    # MENTIONS remain included because each
    # underlying profile contains the core.
    # -------------------------------------------------

    relationship_types = frozenset(
        relationship_type

        for profile_name
        in ordered_names

        for relationship_type
        in (
            ONTOLOGY_PROFILES[
                profile_name
            ]
            .relationship_types
        )
    )

    composed_name = (
        "+".join(
            ordered_names
        )
    )

    return OntologyProfile(
        name=(
            composed_name
        ),

        version=(
            ONTOLOGY_VERSION
        ),

        entity_types=(
            entity_types
        ),

        relationship_types=(
            relationship_types
        ),
    )


# =========================================================
# PROFILE LOOKUP
# =========================================================


def get_ontology_profile(
    name: str,
) -> OntologyProfile:
    """
    Retrieve a TraceGraph ontology profile.

    Supports both registered profiles:

        get_ontology_profile(
            "research"
        )

    and composed profiles:

        get_ontology_profile(
            "policy+contract"
        )
    """

    normalized_name = (
        name.strip()
        .casefold()
    )

    if not normalized_name:
        raise ValueError(
            "Ontology profile name "
            "cannot be empty"
        )

    # -------------------------------------------------
    # Standard registered ontology.
    # -------------------------------------------------

    profile = (
        ONTOLOGY_PROFILES.get(
            normalized_name
        )
    )

    if profile is not None:
        return profile

    # -------------------------------------------------
    # Composed ontology.
    #
    # Example:
    #
    # policy+contract
    #
    # becomes:
    #
    # ["policy", "contract"]
    #
    # and is reconstructed deterministically.
    # -------------------------------------------------

    if "+" in normalized_name:
        component_names = [
            component.strip()

            for component
            in normalized_name.split("+")

            if component.strip()
        ]

        if not component_names:
            raise ValueError(
                "Invalid composed ontology "
                f"profile '{name}'"
            )

        return (
            compose_ontology_profiles(
                component_names
            )
        )

    # -------------------------------------------------
    # Unknown profile.
    # -------------------------------------------------

    valid_profiles = ", ".join(
        sorted(
            ONTOLOGY_PROFILES
        )
    )

    raise ValueError(
        "Unknown ontology profile "
        f"'{name}'. "
        "Valid profiles: "
        f"{valid_profiles}, "
        "or a '+' composition such as "
        "'policy+contract'"
    )