from dataclasses import dataclass

from app.graph.schema import (
    EntityType,
    RelationshipType,
    RELATIONSHIP_GUIDANCE,
)


ONTOLOGY_VERSION = "2.0"


@dataclass(
    frozen=True
)
class OntologyProfile:
    """
    Defines the semantic vocabulary allowed
    for one class of documents.

    Every domain profile contains the
    universal core plus its domain-specific
    extension.

    Profiles may also be composed from
    multiple domain extensions.
    """

    name: str

    version: str

    entity_types: frozenset[
        EntityType
    ]

    relationship_types: frozenset[
        RelationshipType
    ]

    @property
    def entity_type_values(
        self,
    ) -> set[str]:
        return {
            entity_type.value
            for entity_type
            in self.entity_types
        }

    @property
    def relationship_type_values(
        self,
    ) -> set[str]:
        return {
            relationship_type.value
            for relationship_type
            in self.relationship_types
        }

    @property
    def extractable_relationship_types(
        self,
    ) -> frozenset[
        RelationshipType
    ]:
        """
        Relationships generated by the semantic
        graph extractor.

        Structural relationships such as
        CONTAINS and MENTIONS are generated by
        TraceGraph itself and therefore must not
        be requested from the LLM.
        """

        return frozenset(
            relationship_type

            for relationship_type
            in self.relationship_types

            if relationship_type
            not in {
                RelationshipType.CONTAINS,
                RelationshipType.MENTIONS,
            }
        )

    @property
    def extractable_relationship_values(
        self,
    ) -> set[str]:
        return {
            relationship_type.value

            for relationship_type
            in self.extractable_relationship_types
        }

    def get_relationship_guidance(
        self,
    ) -> dict[str, str]:
        """
        Return semantic guidance only for
        relationships enabled by this ontology.
        """

        return {
            relationship_type.value:
                RELATIONSHIP_GUIDANCE[
                    relationship_type.value
                ]

            for relationship_type
            in self.extractable_relationship_types

            if (
                relationship_type.value
                in RELATIONSHIP_GUIDANCE
            )
        }


